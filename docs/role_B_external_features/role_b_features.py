# ---------- Imports ----------
import requests
import numpy as np
import pandas as pd
from pathlib import Path
from datetime import date

OUT = Path("data")
OUT.mkdir(exist_ok=True)

LAT        = -12.9714
LON        = -38.5014
TIMEZONE   = "America/Bahia"
START_DATE = "2024-03-01"
END_DATE   = "2024-05-31"

print("✓ Setup done")

# ---------- 1. Weather ----------
print("\n[1/5] Fetching weather from Open-Meteo ...")
weather_path = OUT / "weather_salvador.csv"

if weather_path.exists():
    print("  Cache found – loading from disk.")
    df_weather = pd.read_csv(weather_path, parse_dates=["timestamp"]).set_index("timestamp")
else:
    resp = requests.get(
        "https://archive-api.open-meteo.com/v1/archive",
        params={
            "latitude":           LAT,
            "longitude":          LON,
            "start_date":         START_DATE,
            "end_date":           END_DATE,
            "hourly":             "precipitation,temperature_2m",
            "timezone":           TIMEZONE,
            "precipitation_unit": "mm",
        },
        timeout=30,
    )
    resp.raise_for_status()
    hourly = resp.json()["hourly"]
    df_weather = pd.DataFrame({
        "timestamp":        pd.to_datetime(hourly["time"]),
        "precipitation_mm": hourly["precipitation"],
        "temperature_2m":   hourly["temperature_2m"],
    }).set_index("timestamp")
    df_weather.to_csv(weather_path)

print(f"  ✓ {len(df_weather)} hourly rows. Preview:")
print(df_weather.head(3).to_string())

# ---------- 2. Holidays ----------
print("\n[2/5] Building holiday calendar ...")
df_holidays = pd.DataFrame([
    {"date": date(2024, 3, 29), "holiday_name": "Good Friday"},
    {"date": date(2024, 4, 21), "holiday_name": "Tiradentes"},
    {"date": date(2024, 5,  1), "holiday_name": "Labour Day"},
])
df_holidays["is_holiday"] = True
df_holidays.to_csv(OUT / "holidays_2024.csv", index=False)
print(f"  ✓ {len(df_holidays)} holidays:")
print(df_holidays.to_string(index=False))

# ---------- 3. Load SUNT boarding (FIXED) ----------
print("\n[3/5] Loading SUNT 5-min boarding data ...")
local_wide = OUT / "boarding_5min_wide.csv"

if local_wide.exists():
    print("  Cache found – loading from disk.")
    df_wide = pd.read_csv(local_wide, parse_dates=[0], index_col=0)
else:
    # ── First: list what files actually exist in the dataset ──
    print("  Checking available files on Hugging Face ...")
    from huggingface_hub import HfApi
    api = HfApi()
    files_in_repo = api.list_repo_files(
        repo_id="labiaufba/SSA_StopBusTimeSeries_5",
        repo_type="dataset"
    )
    files_in_repo = list(files_in_repo)
    print(f"  Files found: {files_in_repo}")

    # ── Find the boarding file (whatever it's called) ──
    boarding_file = None
    for f in files_in_repo:
        if "boarding" in f.lower() and f.endswith(".csv"):
            boarding_file = f
            break

    if boarding_file is None:
        # Print all files so we can see what's there
        print("\n  ⚠ Could not find a boarding CSV. All files in repo:")
        for f in files_in_repo:
            print(f"    {f}")
        raise FileNotFoundError(
            "Could not find boarding CSV. Check the file names printed above "
            "and update the filename manually."
        )

    print(f"  Found boarding file: {boarding_file}")

    from huggingface_hub import hf_hub_download
    hf_path = hf_hub_download(
        repo_id="labiaufba/SSA_StopBusTimeSeries_5",
        filename=boarding_file,
        repo_type="dataset",
    )
    df_wide = pd.read_csv(hf_path, parse_dates=[0], index_col=0)
    df_wide.to_csv(local_wide)
    print(f"  ✓ Saved wide table → {local_wide}")

# Melt wide → long
df_wide.index.name = "timestamp"
df_boarding = df_wide.reset_index().melt(
    id_vars="timestamp", var_name="stop_id", value_name="boardings"
)
df_boarding["boardings"] = pd.to_numeric(
    df_boarding["boardings"], errors="coerce"
).fillna(0.0)
df_boarding = df_boarding.sort_values(
    ["stop_id", "timestamp"]
).reset_index(drop=True)
print(f"  ✓ {len(df_boarding):,} rows × {df_boarding['stop_id'].nunique()} stops")
print(df_boarding.head(3).to_string())

# ---------- 4. Join external data ----------
print("\n[4/5] Joining weather + holidays ...")

df_boarding["timestamp"] = pd.to_datetime(df_boarding["timestamp"])
if df_boarding["timestamp"].dt.tz is not None:
    df_boarding["timestamp"] = (
        df_boarding["timestamp"]
        .dt.tz_convert("America/Bahia")
        .dt.tz_localize(None)
    )

df_weather = df_weather.copy()
df_weather.index = pd.to_datetime(df_weather.index)
if df_weather.index.tz is not None:
    df_weather.index = df_weather.index.tz_localize(None)

df_boarding["hour_ts"] = df_boarding["timestamp"].dt.floor("h")
df_merged = df_boarding.merge(
    df_weather.reset_index().rename(columns={"timestamp": "hour_ts"}),
    on="hour_ts", how="left",
)
df_merged[["precipitation_mm", "temperature_2m"]] = (
    df_merged[["precipitation_mm", "temperature_2m"]].ffill()
)
df_merged.drop(columns=["hour_ts"], inplace=True)

df_holidays["date"] = pd.to_datetime(df_holidays["date"]).dt.date
df_merged["date"] = df_merged["timestamp"].dt.date
df_merged = df_merged.merge(
    df_holidays[["date", "is_holiday", "holiday_name"]],
    on="date", how="left",
)
df_merged["is_holiday"]   = df_merged["is_holiday"].fillna(False).astype(bool)
df_merged["holiday_name"] = df_merged["holiday_name"].fillna("")
df_merged.drop(columns=["date"], inplace=True)
print(f"  ✓ Merged shape: {df_merged.shape}")

# ---------- 5. Build streaming features ----------
print("\n[5/5] Building streaming features ...")
LAG_STEPS       = [1, 2, 3, 6, 12]
ROLLING_WINDOWS = [6, 12]

dfs = []
for stop_id, grp in df_merged.groupby("stop_id", sort=False):
    grp = grp.sort_values("timestamp").copy()
    ts  = grp["timestamp"]

    grp["hour_of_day"]    = ts.dt.hour + ts.dt.minute / 60.0
    grp["minute_of_hour"] = ts.dt.minute
    grp["sin_hour"]       = np.sin(2 * np.pi * ts.dt.hour / 24)
    grp["cos_hour"]       = np.cos(2 * np.pi * ts.dt.hour / 24)
    grp["day_of_week"]    = ts.dt.dayofweek
    grp["is_weekend"]     = grp["day_of_week"] >= 5
    grp["week_of_year"]   = ts.dt.isocalendar().week.astype(int)
    grp["day_type"]       = np.where(
        grp["is_holiday"], "holiday",
        np.where(grp["is_weekend"], "weekend", "weekday")
    )

    for k in LAG_STEPS:
        grp[f"boarding_lag_{k}"] = grp["boardings"].shift(k)

    for w in ROLLING_WINDOWS:
        grp[f"rolling_mean_{w}"] = (
            grp["boardings"].shift(1).rolling(w, min_periods=1).mean()
        )
        grp[f"rolling_std_{w}"] = (
            grp["boardings"].shift(1).rolling(w, min_periods=1).std().fillna(0)
        )

    grp["is_raining"] = grp["precipitation_mm"] > 0.1
    grp["rain_intensity"] = pd.cut(
        grp["precipitation_mm"],
        bins=[-np.inf, 0.1, 2.5, 7.6, np.inf],
        labels=["none", "light", "moderate", "heavy"],
    )
    dfs.append(grp)

df_features = (
    pd.concat(dfs, ignore_index=True)
    .sort_values(["timestamp", "stop_id"])
    .reset_index(drop=True)
)
lag_cols = [c for c in df_features.columns
            if c.startswith("boarding_lag_") or c.startswith("rolling_")]
df_features[lag_cols] = df_features[lag_cols].fillna(0.0)

# ---------- Save ----------
out_path = OUT / "features_stream.csv"
df_features.to_csv(out_path, index=False)

print(f"\n✓ Saved → {out_path}  ({out_path.stat().st_size / 1e6:.1f} MB)")
print(f"  Shape: {df_features.shape}")
print(f"\n── Columns ──\n  {list(df_features.columns)}")
print(f"\n── Day-type distribution ──\n{df_features['day_type'].value_counts().to_string()}")
print(f"\n── Rain distribution ──\n{df_features['rain_intensity'].value_counts().to_string()}")
print(f"\n── Stops ──\n  {df_features['stop_id'].unique().tolist()}")

missing = df_features.isnull().sum()
print(f"\n── Missing values ──")
print(missing[missing > 0].to_string() if missing.any() else "  None ✓")

print("\n🎉 Role B complete! Downloading files now ...")

